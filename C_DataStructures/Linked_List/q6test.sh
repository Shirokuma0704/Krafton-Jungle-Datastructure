#!/usr/bin/env bash
# Q6 moveMaxToFront 검산기
#
#   bash q6test.sh        기대값 대조만 (빠름)
#   bash q6test.sh -v     valgrind 까지 (느림)
#
#     check "리스트값들" "기대결과"
#
# 값은 공백으로 구분합니다. 빈 리스트는 "" 를, 기대 출력이 비어 있어야 하면
# "$EMPTY" 를 씁니다.
#
# 이 문제는 함수가 ListNode ** 를 받아서 노드를 직접 재연결해요. 그래서
# 답이 맞아 보여도 끊어낸 자리의 링크가 남아 있을 수 있습니다. -v 로 한 번
# 돌려보시는 게 좋아요.

set -u
cd "$(dirname "$0")"

SRC=Q6_A_LL.c
. ../common/testlib.sh

check() {                # check "리스트값들" "기대결과"
	local vals="$1" want="$2" inp got

	inp=$(menu "$vals" "2\n0\n")
	run "$inp"
	died "$vals" && return

	got=$(pick "맨 앞으로 옮긴" "$OUT")
	if judge "$vals" "최댓값 앞으로" "$got" "$want"; then
		ok "$vals"
	fi

	vgcheck "$inp" "$vals"
}

echo "=== 문제지 예시 ==="
check "30 20 40 70 50"   "70 30 20 40 50"

echo "=== 내가 만든 경계 케이스 ==="
# 여기를 채우세요. 아래는 어떤 상황을 확인하는 칸인지만 적어뒀습니다.
# 주석을 하나씩 풀면서 ? 자리에 기대값을 넣으면 됩니다.
#
# (1) 원소가 아예 없을 때. 옮길 최댓값 자체가 없습니다.
 check "" "$EMPTY"
#
# (2) 원소가 하나뿐일 때. 그게 곧 최댓값이에요.
 check "7" "7"
#
# (3) 최댓값이 이미 맨 앞에 있을 때. 옮길 필요가 없는데 옮기면 깨집니다.
 check "9 1 2 3" "9 1 2 3"
#
# (4) 최댓값이 맨 끝에 있을 때. 끊어낸 자리 뒤에 아무것도 없습니다.
 check "1 2 3 9" "9 1 2 3"
#
# (5) 최댓값이 두 번째에 있을 때. 떼어낼 노드와 맨 앞 노드가 붙어 있습니다.
 check "1 9 2 3" "9 1 2 3"
#
# (6) 최댓값이 여러 개일 때. 어느 것을 옮길지 먼저 정해야 기대값이 써집니다.
 check "3 9 5 9 1" "9 3 5 9 1"
#
# (7) 값이 전부 음수일 때.
 check "-5 -2 -9" "-2 -5 -9"
#
# (8) 값이 전부 같을 때.
 check "4 4 4 4" "4 4 4 4"

summary
