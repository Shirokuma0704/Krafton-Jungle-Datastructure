#!/usr/bin/env bash
# Q2 createStackFromLinkedList / removeEvenValues 검산기
#
#   bash q2test.sh        기대값 대조만 (빠름)
#   bash q2test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "리스트값들" "기대 스택" "짝수 뺀 기대 결과"
#     twice "리스트값들" "두 번째로 만든 스택의 기대값"
#
# 값은 공백으로 구분합니다. 빈 리스트는 "" 를, 출력이 비어 있어야 하면
# "$EMPTY" 를 씁니다.
#
# check 는 메뉴를 1..(값 넣기) → 2(스택 만들기) → 3(짝수 빼기) → 0 순서로 눌러줍니다.
# 두 함수를 한 번에 보기 때문에, 스택 만들기부터 틀렸으면 그 줄에서 먼저 걸립니다.
#
# twice 는 2 를 연속으로 두 번 누릅니다. createStackFromLinkedList 가
# 이전 스택을 제대로 치우고 시작하는지 보려는 용도예요.
#
# 기대값을 적을 때 한 가지만 조심하세요. 스택은 후입선출이라
# 리스트 순서와 출력 순서가 뒤집힙니다. Q1 의 큐와 정반대예요.
#
# gcc 찾기 / 컴파일 / 타임아웃 / 출력 비교 / valgrind / 집계는 전부
# ../common/testlib.sh 에 있습니다. 여기엔 Q2 에서만 다른 것만 있어요.

set -u
cd "$(dirname "$0")"

SRC=Q2_C_SQ.c
. ../common/testlib.sh

check() {                # check "리스트값들" "기대 스택" "짝수 뺀 기대 결과"
	local vals="$1" wants="$2" wanto="$3"
	local inp gots goto

	inp=$(menu "$vals" "2\n3\n0\n")
	run "$inp"
	died "$vals" && return

	gots=$(pick "만들어진 스택" "$OUT")
	goto=$(pick "짝수를 뺀 스택" "$OUT")

	if judge "$vals" "스택 만들기" "$gots" "$wants" \
	   && judge "$vals" "짝수 빼기" "$goto" "$wanto"; then
		ok "$vals"
	fi

	vgcheck "$inp" "$vals"
}

twice() {                # twice "리스트값들" "두 번째로 만든 스택의 기대값"
	local vals="$1" want="$2" inp got

	inp=$(menu "$vals" "2\n2\n0\n")
	run "$inp"
	died "2연속:$vals" && return

	got=$(pick "만들어진 스택" "$OUT" 2)
	if judge "2연속:$vals" "두 번째 스택" "$got" "$want"; then
		ok "2연속:$vals"
	fi
}

echo "=== 기본 ==="
# 문제지에 나온 예시 그대로예요. 뒤집혀 나오는 게 정상입니다.
check "1 3 5 6 7" "7 6 5 3 1" "7 5 3 1"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 줄 채울 때마다 돌리시는 게 좋아요. 열 줄 한꺼번에 채우고 돌리면
# 어느 줄이 왜 틀렸는지 다시 찾아야 하거든요.
#
# (1) 리스트가 비어 있을 때. 스택 만들기와 짝수 빼기가 둘 다 빈 것을 받습니다.
# check "" "?" "?"
#
# (2) 원소가 하나뿐인데 그게 홀수일 때. 아무것도 안 빠집니다.
# check "3" "?" "?"
#
# (3) 원소가 하나뿐인데 그게 짝수일 때. 스택이 텅 비게 됩니다.
# check "2" "?" "?"
#
# (4) 전부 홀수일 때. 아무것도 안 빠지는데, 그러고도 순서가 그대로인지가 핵심입니다.
# check "1 3 5 7" "?" "?"
#
# (5) 전부 짝수일 때. 스택이 완전히 비워집니다.
# check "2 4 6 8" "?" "?"
#
# (6) 짝수가 스택의 맨 위에만 하나 있을 때.
#     스택 맨 위는 리스트의 어느 쪽 끝인지부터 정하고 적으세요.
# check "?" "?" "?"
#
# (7) 짝수가 스택의 맨 바닥에만 하나 있을 때. (6) 과 방향이 반대입니다.
# check "?" "?" "?"
#
# (8) 0 이 섞여 있을 때. 0 을 짝수로 보는지 확인합니다.
# check "0 1 3" "?" "?"
#
# (9) 음수 짝수가 섞여 있을 때. C 에서 -4 % 2 가 무엇인지 먼저 생각해보세요.
# check "-2 -3 -4 -5" "?" "?"
#
# (10) 같은 값이 여러 번 나올 때. 하나만 지우고 마는지 봅니다.
# check "2 3 2 3" "?" "?"

echo "=== 스택 만들기를 두 번 연속 ==="
# 2 를 눌러 스택을 만든 뒤, 곧바로 2 를 한 번 더 누릅니다.
# 두 번째 시점에 연결 리스트가 어떤 상태인지부터 정하고, 그러면 스택이
# 어떻게 되어야 맞는지를 정해서 적으세요.
# twice "1 3 5" "?"

