#!/usr/bin/env bash
# Q7 balanced 검산기
#
#   bash q7test.sh        기대값 대조만 (빠름)
#   bash q7test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "식"  "$YES"  또는  "$NO"
#     twice "식1" "판정1" "식2" "판정2"      한 세션에서 두 번 검사
#
# ★ 지금까지와 입력이 완전히 다릅니다 ★
# 정수를 여러 개 넣는 게 아니라 **문자열 하나**를 받습니다. 그래서 menu 를 안 쓰고
# check 안에서 직접 "1 / 식 / 2 / 0" 을 만들어요.
#
# 결과는 Q3 처럼 문장이라 기대값 자리에 $YES / $NO 를 씁니다.
#
#     YES = 괄호가 맞습니다!
#     NO  = 괄호가 안 맞습니다!
#
# twice 는 한 번 검사한 뒤 다른 식을 넣어 한 번 더 검사합니다. 첫 번째 검사에서
# 쓰던 것이 남아 있으면 두 번째가 흔들리거든요.
#
# 알아두실 제약 하나: **빈 문자열은 이 메뉴로 못 넣습니다.** scanf("%s", ...) 가
# 공백을 건너뛰고 최소 한 글자를 요구해서, 그냥 엔터를 치면 다음 줄을 먹어버려요.
# 그래서 "빈 식" 케이스는 여기서 못 만듭니다. 함수 안에서는 대비해두시고,
# 확인은 내일 LeetCode 20 번에서 하시면 됩니다. 거기선 빈 문자열이 입력으로 들어와요.
#
# 판정이 전부 반대로 나오면 main 이 무엇을 참으로 치는지부터 보세요. Q3 에서 겪은 그 자리예요.
#
# 디버거로 돌리실 거면 main 맨 위에 setvbuf(stdout, NULL, _IONBF, 0); 넣어두시고요.

set -u
cd "$(dirname "$0")"

SRC=Q7_C_SQ.c
. ../common/testlib.sh

YES="괄호가 맞습니다!"
NO="괄호가 안 맞습니다!"

VERDICT='맞습니다!'        # "맞습니다!" 와 "안 맞습니다!" 를 둘 다 잡습니다.
                           # 메뉴 안내문은 "맞는지" 라서 안 걸려요.

check() {                # check "식" "기대 판정"
	local expr="$1" want="$2" inp got

	inp="1\n$expr\n2\n0\n"
	run "$inp"
	died "$expr" && return

	got=$(pick "$VERDICT" "$OUT")
	if judge "$expr" "판정" "$got" "$want"; then
		ok "$expr"
	fi

	vgcheck "$inp" "$expr"
}

twice() {                # twice "식1" "판정1" "식2" "판정2"
	local e1="$1" w1="$2" e2="$3" w2="$4" inp g1 g2 name

	inp="1\n$e1\n2\n1\n$e2\n2\n0\n"
	name="$e1 그다음 $e2"
	run "$inp"
	died "$name" && return

	g1=$(pick "$VERDICT" "$OUT" 1)
	g2=$(pick "$VERDICT" "$OUT" 2)

	if judge "$name" "첫 번째" "$g1" "$w1" \
	   && judge "$name" "두 번째" "$g2" "$w2"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

echo "=== 문제지 예시 ==="
# 짝이 맞는 식 세 개 중 하나, 안 맞는 식 두 개 중 하나만 채워뒀어요.
check "{[]()[]}" "$YES"
check "[({{)])"  "$NO"
