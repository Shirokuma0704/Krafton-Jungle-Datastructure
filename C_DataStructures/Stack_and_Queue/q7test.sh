#
# (1) 여는 괄호 하나뿐일 때. 끝까지 갔는데 스택에 뭔가 남아 있는 경우예요.
# check "(" "?"
#
# (2) 닫는 괄호 하나뿐일 때. 스택이 비어 있는데 닫으려는 경우고요. (1) 과 원인이 다릅니다.
# check ")" "?"
#
# (3) 개수는 맞는데 순서가 뒤집혔을 때. 개수만 세는 풀이가 여기서 걸립니다.
# check ")(" "?"
#
# (4) 짝은 맞춰 닫았는데 종류가 다를 때.
# check "(]" "?"
#
# (5) 종류가 서로 엇갈려 닫힐 때. (4) 보다 한 단계 더 꼬인 모양이에요.
# check "([)]" "?"
#
# (6) 여는 괄호만 여러 개일 때.
# check "?" "?"
#
# (7) 닫는 괄호만 여러 개일 때.
# check "?" "?"
#
# (8) 제대로 깊게 중첩됐을 때. 스택이 실제로 쌓였다 풀리는지 봅니다.
# check "?" "?"
#
# (9) 같은 종류가 연달아 나올 때. 쌓이지 않고 바로바로 풀리는 모양입니다.
# check "?" "?"

