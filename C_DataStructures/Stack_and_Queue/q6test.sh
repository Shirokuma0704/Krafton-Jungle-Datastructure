check() {                # check "넣는 순서" "뺄 값" "기대 스택"
	local vals="$1" target="$2" want="$3" inp got stack name

	inp=$(menu "$vals" "2\n$target\n0\n")
	name="$vals  ->  $target"
	run "$inp"
	died "$name" && return

	got=$(pick "지정한 값까지 뺀 스택" "$OUT")
	if judge "$name" "빼기" "$got" "$want"; then
		ok "$name"
	else
		# 넣는 순서와 찍히는 순서가 반대라 헷갈리기 쉬워요. 빼기 전 스택을 같이 보여줍니다.
		stack=$(pick "만들어진 스택" "$OUT" '$')
		printf '          빼기 전 스택: [%s]\n' "$stack"
	fi

	vgcheck "$inp" "$name"
}

echo "=== 문제지 예시 ==="
# 예시 1. 스택이 1 2 3 4 5 6 7 (맨 왼쪽이 top) 이고 4 까지 빼면 4 5 6 7 이 남아요.
#         찍히는 게 1 2 3 ... 이어야 하니 넣는 순서는 그 반대입니다.
check "7 6 5 4 3 2 1" "4" "4 5 6 7"
