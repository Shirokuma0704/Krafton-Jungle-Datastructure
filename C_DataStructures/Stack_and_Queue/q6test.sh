# 문제지 예시를 옮길 때는 예시의 스택을 뒤집어서 "넣는 순서" 칸에 적으세요.
# 틀리면 FAIL 날 때 그때의 스택을 같이 찍어주니 거기서 확인하시면 됩니다.
#
# 참고: main 의 메뉴 안내가 "3: 지정한 값이 나올 때까지 빼기" 라고 찍는데
# 실제로 동작하는 건 case 2 입니다. 과제 템플릿의 오타예요. 검산기는 2 를 누릅니다.
