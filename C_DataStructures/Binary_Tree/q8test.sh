#!/usr/bin/env bash
# Q8 hasGreatGrandchild 검산기
#
#   bash q8test.sh        기대값 대조만 (빠름)
#   bash q8test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" "찍혀야 할 값들"
#     shape "이름" "트리"                 내가 적은 대로 만들어졌는지만 확인
#
# 트리 적는 법은 q2~q7 과 같아요. 보이는 대로 적고, 중간 빈 자리만 x 로 표시합니다.
#
# ★ 이번엔 세 층 아래를 봐야 합니다 ★
#
# 지금까지는 노드 하나와 그 자식들만 보면 됐어요. 이건 손자의 자식, 그러니까
# 증손자까지 내려다봐야 합니다. 관계를 한 번 정리하고 가면 편해요.
#
#       나
#       └ 자식        1층 아래
#         └ 손자      2층 아래
#           └ 증손자  3층 아래      ← 이게 하나라도 있으면 "나" 를 찍습니다
#
# 문제지 그림입니다.
#
#          50               적는 법: 50 30 60 25 65 10 75 x x 20 15
#         /  \
#       30    60            출력: 50
#      /  \   / \           50 -> 30 -> 65 -> 20 으로 3층 아래에 증손자가 있어요.
#    25   65 10  75
#         / \                30 은 손자(20, 15)까지만 있고 증손자가 없어서 안 찍힙니다.
#       20   15              한 층 차이로 갈리는 자리예요.
#
# ★ 기대값은 "찍혀 나올 값들" 입니다 ★
#
# Q6 처럼 출력하는 함수예요. main 이 앞머리를 찍어두고, 가운데를 이 함수가 채웁니다.
# 아무것도 안 찍혀야 하면 기대값 자리에 "$EMPTY" 나 "" 를 쓰세요.
#
# 다만 Q6 과 달리 **순서는 안 봅니다.** 문제지 예시에 값이 하나뿐이라 어떤 순서로
# 찍어야 하는지가 정해져 있지 않아요. 그래서 양쪽 값을 정렬해서 비교합니다.
# 값의 집합만 맞으면 통과예요.
#
# 알아두실 제약 하나: main 의 case 2 가 이 함수를 부른 뒤 줄바꿈을 안 찍습니다.
# 그래서 찍힌 값들이 다음 메뉴 프롬프트와 같은 줄에 붙어서 나와요. 눈으로 보실
# 때 지저분해 보여도 정상이고, 검산기는 앞뒤를 잘라내고 값만 봅니다.
#
# 함수 원형이 int 인데 main 은 반환값을 안 씁니다. 그러니 눈에 보이는 결과는
# 찍힌 줄 하나뿐이에요. 반환값을 무엇으로 쓸지는 문제지 여백 메모에 힌트가 있습니다.

set -u
cd "$(dirname "$0")"

SRC=Q8_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

tree() {                 # tree "50 30 60"  ->  "50\n30\n60\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

# 순서를 안 보므로 양쪽 다 정렬해서 맞춰봅니다.
sortvals() {
	printf '%s' "$1" | tr ' ' '\n' | grep -v '^$' | sort -n | tr '\n' ' ' | sed 's/ $//'
}

check() {                # check "이름" "트리" "찍혀야 할 값들"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	# main 이 이 함수 뒤에 줄바꿈을 안 찍어서, 찍힌 값이 다음 프롬프트와
	# 같은 줄에 붙어 나옵니다. 그래서 앞뒤를 직접 잘라냅니다.
	got=$(printf '%s\n' "$OUT" | grep -m1 '노드들의 값:' |
	      sed 's/.*노드들의 값: //; s/원하는 번호를.*//; s/[[:space:]]*$//')

	got=$(sortvals "$got")
	want=$(sortvals "$want")
	[ -z "$got" ] && got="$EMPTY"
	[ -z "$want" ] && want="$EMPTY"

	if judge "$name" "찍힌 값" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

# 내가 적은 트리대로 프로그램이 만들었는지만 봅니다. 기대값은 안 적어도 돼요.
shape() {                # shape "이름" "트리"
	local name="$1" t1="$2" want got inp

	want=$(lv_to_inorder "$t1")
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "만들어진 트리" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
shape "문제지 그림" "50 30 60 25 65 10 75 x x 20 15"

echo "=== 문제지 예시 ==="
check "문제지 그림" "50 30 60 25 65 10 75 x x 20 15" "50"

echo "=== 기본 ==="
check "한 노드" "1" "$EMPTY"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 찍을 게 없으니 아무것도 안 나와야 해요.
#     여기서 NULL 을 안 걸러내면 없는 노드의 자식을 들여다봅니다.
 check "빈 트리" "?" "$EMPTY"
#
# (2) 딱 세 층짜리 트리. 손자까지는 있는데 증손자가 없는 경우예요.
#     문제지의 30 이 이 자리입니다. 한 층 차이로 안 찍혀야 하는데,
#     "손자가 있으면" 으로 세면 여기서 찍혀버립니다.
 check "손자까지만" "1 2 3" "$EMPTY"
#
# (3) (2) 에 한 층만 더 붙인 트리. 같은 트리에서 한 층 차이로 결과가 뒤집히는지
#     보는 자리예요. (2) 와 짝으로 만드시면 비교가 선명합니다.
 check "네 층" "1 2 3 4 5 6 7 8 x" "1"
#
# (4) 증손자를 가진 노드가 둘 이상인 트리. 한 노드만 찾고 멈추는 구현이
#     여기서 드러나요. 다섯 층 이상이면 위쪽 두 노드가 같이 해당됩니다.
 check "여러 개" "
 1
  L2
    L4
      L7
        L8
  R3" "2 1"
#
# (5) 한쪽 가지만 깊고 반대쪽은 얕은 트리. 얕은 쪽 때문에 깊은 쪽 판단이
#     묻히지 않는지 보는 자리입니다. 좌우를 바꿔서 한 번 더 해보셔도 좋아요.
 check "한쪽만 깊음" "
 1
  L8
    L7
      R9
        L8
  R3
    L2" "8 1"

summary
