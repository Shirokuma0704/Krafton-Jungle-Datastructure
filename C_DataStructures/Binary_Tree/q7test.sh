#!/usr/bin/env bash
# Q7 smallestValue 검산기
#
#   bash q7test.sh        기대값 대조만 (빠름)
#   bash q7test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" 기대값
#     shape "이름" "트리"                 내가 적은 대로 만들어졌는지만 확인
#
# 트리 적는 법은 q2~q6 와 같아요. 보이는 대로 적고, 중간 빈 자리만 x 로 표시합니다.
#
# 기대값은 다시 **숫자 하나** 입니다. 값을 돌려주는 함수로 돌아왔어요.
#
#          50          최솟값: 10
#         /  \
#       30    60       적는 법: 50 30 60 25 65 10 75
#      /  \  /  \
#    25   65 10  75
#
# ★ 문제지가 못박아둔 것 ★
#
# "탐색 트리가 아니라서 '왼쪽 끝까지 내려가면 최솟값' 이 성립하지 않습니다."
#
# 위 그림이 그 반례예요. 왼쪽 끝은 25 인데 최솟값은 오른쪽에 있는 10 입니다.
# Q6 과 같은 트리이고, 같은 이유로 가지치기가 안 돼요. 모든 노드를 다 봐야 합니다.
#
# ★ 빈 트리는 문제지가 안 정해줬습니다 ★
#
# 값이 하나도 없는데 "가장 작은 값" 을 int 로 돌려줘야 해요. 정답이 정해져
# 있지 않으니 **직접 정하고 그 값을 아래 (1) 번에 적으시면** 됩니다.
# 무엇으로 정하든, 노드가 있는 트리들의 답이 안 틀어지는 값이어야 해요.

set -u
cd "$(dirname "$0")"

SRC=Q7_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

LABEL='최솟값:'          # 메뉴 안내문은 "최솟값;" 이라 안 걸립니다.

tree() {                 # tree "50 30 60"  ->  "50\n30\n60\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

check() {                # check "이름" "트리" 기대값
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "$LABEL" "$OUT")
	if judge "$name" "최솟값" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

# 내가 적은 트리대로 프로그램이 만들었는지만 봅니다. 기대값은 안 적어도 돼요.
shape() {                # shape "이름" "트리"
	local name="$1" t1="$2" want got inp

	want=$(lv_to_inorder "$t1")
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "만들어진 트리" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
shape "문제지 그림" "50 30 60 25 65 10 75"

echo "=== 문제지 예시 ==="
check "문제지 그림" "50 30 60 25 65 10 75" "10"

echo "=== 기본 ==="
check "한 노드" "7" "7"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 문제지가 값을 안 정해줬으니 먼저 정하고 그 값을 적으세요.
#     노드가 있는 트리들의 답이 안 틀어지는 값이어야 합니다.
 check "빈 트리" "" "0" #Return 0라서
#
# (2) 최솟값이 루트에 있는 트리. 루트를 후보에서 빠뜨리는 구현이 여기서
#     드러나요. 자식들만 비교하고 자기 값을 안 보면 걸립니다.
 check "최솟값이 루트" "-5 2 3 4 5 8 7" "-5"
#
# (3) 최솟값이 오른쪽 깊은 곳에 있는 트리. 왼쪽만 파고 내려가는 구현이
#     여기서 걸려요. 문제지가 성립하지 않는다고 못박은 그 자리입니다.
 check "최솟값이 오른쪽 끝" "7 8 2 4 2 7 0" "0"
#
# (4) 값이 전부 음수인 트리. 후보의 출발점을 무엇으로 잡았는지가 여기서
#     드러납니다.
 check "전부 음수" "-5 -7 -9 -3 -5 -4 -7" "-9"
#
# (5) 최솟값이 잎이 아니라 중간 노드에 있는 트리. 잎만 후보로 보는 구현이
#     여기서 걸려요. 최솟값 아래에 더 큰 값이 달려 있게 만들어보세요.
 check "최솟값이 중간 노드" "1 2 3 -100 5 6 7" "-100"

summary
