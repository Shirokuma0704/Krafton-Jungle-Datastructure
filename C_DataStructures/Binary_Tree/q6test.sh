#!/usr/bin/env bash
# Q6 printSmallerValues 검산기
#
#   bash q6test.sh        기대값 대조만 (빠름)
#   bash q6test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" 기준값 "찍혀야 할 값들"
#     shape "이름" "트리"                 내가 적은 대로 만들어졌는지만 확인
#
# 트리 적는 법은 q2~q5 와 같아요. 보이는 대로 적고, 중간 빈 자리만 x 로 표시합니다.
#
# ★ 이번엔 기대값이 트리가 아니라 "찍혀 나올 줄" 입니다 ★
#
# Q5 는 트리를 바꾸는 함수라 결과도 트리였는데, 이건 **출력하는** 함수예요.
# 돌려주는 값도 없고 트리도 안 바뀝니다. 남는 건 화면에 찍힌 줄뿐이에요.
# 그래서 기대값 자리에는 찍혀야 할 숫자들을 순서대로 적습니다.
#
# 아무것도 안 찍혀야 하면 기대값 자리에 "$EMPTY" 를 쓰세요.
#
# ★ 순서 ★
#
# 문제지 예시가 이렇습니다.
#
#          50          기준값 55 로 부르면  ->  50, 30, 25, 10
#         /  \
#       30    60       루트를 먼저 찍고, 왼쪽으로 내려갔다가, 오른쪽으로 갑니다.
#      /  \  /  \      (50 -> 30 -> 25 -> [65 는 큼] -> 60 은 큼 -> 10 -> 75 는 큼)
#    25   65 10  75
#
#                      적는 법: 50 30 60 25 65 10 75
#
# 값만 맞고 순서가 다르면 FAIL 이 뜹니다. 그때는 나온것/기대값 두 줄을 나란히
# 보시면 어디서 갈렸는지 바로 보여요.
#
# ★ 이 트리는 이진 탐색 트리가 아닙니다 ★
#
# 문제지가 굳이 못박아 뒀어요. 30 아래에 65 가 달려 있죠. 그래서 "이쪽은 다
# 작으니까 안 봐도 된다" 같은 가지치기가 안 됩니다. 모든 노드를 다 봐야 해요.
#
# 알아두실 제약 하나: case 2 가 찍고 나서 removeAll 을 해버려서, 한 트리에
# 기준값을 바꿔가며 두 번 물어볼 수가 없습니다. 기준값 하나에 트리 하나예요.

set -u
cd "$(dirname "$0")"

SRC=Q6_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

tree() {                 # tree "50 30 60"  ->  "50\n30\n60\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

check() {                # check "이름" "트리" 기준값 "찍혀야 할 값들"
	local name="$1" t1="$2" m="$3" want="$4" inp got

	# 기대값을 빈 문자열로 적으셔도 "아무것도 안 찍힘" 으로 읽습니다.
	# "$EMPTY" 라고 쓰든 "" 라고 쓰든 같아요.
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")2\n$m\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "보다 작은 값들:" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "찍힌 값" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

# 내가 적은 트리대로 프로그램이 만들었는지만 봅니다. 기대값은 안 적어도 돼요.
shape() {                # shape "이름" "트리"
	local name="$1" t1="$2" want got inp

	want=$(lv_to_inorder "$t1")
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "만들어진 트리" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
shape "문제지 그림" "50 30 60 25 65 10 75"

echo "=== 문제지 예시 ==="
check "문제지 그림" "50 30 60 25 65 10 75" 55 "50 30 25 10"

echo "=== 기본 ==="
check "한 노드, 기준보다 작음" "1" 10 "1"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 찍을 게 없으니 아무것도 안 나와야 해요.
#     여기서 NULL 을 안 걸러내면 없는 노드의 값을 읽습니다.
 check "빈 트리" "" 10 "$EMPTY"
#
# (2) 모든 값이 기준값보다 큰 트리. 결과는 (1) 과 같이 빈 줄인데 지나온 길이
#     완전히 달라요. 노드를 다 돌고도 하나도 안 찍어야 합니다.
 check "전부 기준보다 큼" "10 50 40 30 x 50 10" "-1" "$EMPTY"
#
# (3) 모든 값이 기준값보다 작은 트리. (2) 의 반대쪽이고, 빠뜨리는 노드가
#     없는지 봅니다. 순서까지 맞아야 해요.
 check "전부 기준보다 작음" "1 2 3 4 5 6 7" "500" "1 2 4 5 3 6 7"
#
# (4) 기준값과 **정확히 같은** 값이 들어 있는 트리. 문제지가 "작은 값" 이라고
#     했으니, 같은 값이 찍혀야 하는지 아닌지를 먼저 정하고 적으세요.
 check "기준값과 같은 값" "0 0 0 0 0 0 0" "0" ""
#
# (5) 음수와 0 이 섞인 트리. 기준값도 음수로 한 번 줘보세요.
#     크기 비교가 음수 구간에서도 그대로 도는지 보는 자리입니다.
# check "음수 구간" "?" "?" "?" 위에서 처리함

summary
