#!/usr/bin/env bash
# Q4 sumOfOddNodes 검산기
#
#   bash q4test.sh        기대값 대조만 (빠름)
#   bash q4test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" "기대 총합"
#     shape "이름" "트리" "중위순회 기대값"      입력이 내 생각대로 들어갔는지
#
# 트리 적는 법은 q2·q3 와 같아요. **위에서 아래로, 왼쪽에서 오른쪽으로** 보이는
# 대로 적고, 중간에 빈 자리만 x 로 표시합니다. 뒤쪽 빈 자리는 생략해도 돼요.
#
#          50               적는 법:  50 40 60 11 35 80 85
#         /  \
#       40    60            홀수는 11, 35, 85 → 총합 131
#      /  \  /  \
#    11   35 80  85
#
# ★ "홀수" 를 어떻게 판별하느냐가 이 문제의 전부입니다 ★
#
# 값이 전부 양수면 어떻게 짜도 대개 맞습니다. 갈리는 건 **음수와 0** 이에요.
# 아래 (4)(5) 가 그 자리입니다.
#
# 출력 끝에 마침표가 붙어서 나오는데("... 총합: 131."), 검산기가 떼고 비교합니다.

set -u
cd "$(dirname "$0")"

SRC=Q4_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

LABEL='홀수 총합:'       # 메뉴 안내문은 "홀수 전부 더하기." 라서 안 걸립니다.

tree() {                 # tree "50 40 60"  ->  "50\n40\n60\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

check() {                # check "이름" "트리" "기대 총합"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "$LABEL" "$OUT")
	got=${got%.}         # 출력 끝의 마침표를 뗍니다

	if judge "$name" "총합" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

shape() {                # shape "이름" "트리" "중위순회 기대값"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "중위순회" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
# 총합을 믿으려면 트리부터 맞아야 해요. 여기가 틀리면 아래는 볼 필요도 없습니다.
shape "문제지 그림" "50 40 60 11 35 80 85" "11 40 35 50 80 60 85"

echo "=== 문제지 예시 ==="
check "문제지 그림" "50 40 60 11 35 80 85" "131"

echo "=== 기본 ==="
check "한 노드, 홀수" "7" "7"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 재귀가 맨 아래에서 마주치는 경우이고, 더하기의 출발점이
#     무엇이어야 하는지를 정하는 자리예요.
 check "빈 트리" "" "0"
#
# (2) 홀수가 하나도 없는 트리. 답은 (1) 과 같은 값이 나오지만 지나온 길이
#     완전히 달라요. 노드를 다 돌고도 아무것도 안 더해야 합니다.
 check "홀수가 없음" "2 4 6 8 2 4 6" "0"
#
# (3) 모든 값이 홀수인 트리. (2) 의 반대쪽이고, 빠뜨리는 노드가 없는지 봅니다.
#     손으로 더한 값을 기대값에 적으세요.
 check "전부 홀수" "1 3 5 7 1 3 5" "25"
#
# (4) 음수가 섞인 트리. C 에서 나머지 연산이 음수에 대해 어떻게 동작하는지가
#     여기서 드러납니다. 음수 홀수를 하나 이상 넣어보세요.
 check "음수 섞임" "-1 -2 -3 4 5 -1 0" "0"
#
# (5) 0 이 들어 있는 트리. 0 이 홀수인지 짝수인지 먼저 정하고, 그 판단이
#     코드에서도 같게 나오는지 보는 자리예요.
 check "0 포함" "0 2 3" "3"

summary
