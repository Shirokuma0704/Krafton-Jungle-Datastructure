#!/usr/bin/env bash
# Q2 maxHeight 검산기
#
#   bash q2test.sh        기대값 대조만 (빠름)
#   bash q2test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" "기대 높이"
#     shape "이름" "트리" "중위순회 기대값"      입력이 내 생각대로 들어갔는지
#
# ★ 트리 적는 법이 q1test.sh 와 달라졌어요 ★
#
# q1 에서는 createTree 가 묻는 순서(스택에서 꺼내는 순서)로 적어야 했는데, 그게
# 머릿속 그림을 번역하는 별도 작업이라 손이 너무 많이 갔습니다. 그래서 **위에서
# 아래로, 왼쪽에서 오른쪽으로** 읽는 순서로 바꿨어요. 아침에 LeetCode 에서
# 쓰시던 그 방식입니다.
#
#          4              적는 법:  4 2 6 1 3 5 7
#         / \                       └┘ └─┘ └─────┘
#        2   6                      1층  2층    3층
#       / \ / \
#      1  3 5  7
#
# 빈 자리에는 문자를 하나 넣습니다. 보통 x 를 써요.
#
#      1                  적는 법:  1 x 2        루트에 왼쪽이 없으니 x
#       \
#        2
#
#      1                  적는 법:  1 2 x 3 x 4
#     /                             왼쪽으로만 내려가는 줄이에요.
#    2                              층마다 "왼쪽, 오른쪽" 이라 x 가 하나씩 껴요.
#   /
#  3
# /
# 4
#
# **뒤쪽 빈 자리는 안 적어도 됩니다.** 잎의 자식들은 알아서 채워져요.
# 빈 트리는 문자 하나만 ("x") 주면 됩니다.
#
# 변환은 ../common/treeinput.sh 가 합니다. q1test.sh 는 이미 끝난 파일이라
# 그대로 뒀어요. 앞으로 만드는 트리 검산기는 전부 이 방식입니다.
#
# ★ 높이를 어떻게 세는지가 이 문제의 전부입니다 ★
#
# 문제지에 정의가 적혀 있어요. **노드 개수가 아니라 링크 개수** 입니다.
#
#        4          4 에서 1 까지 내려가려면 링크를 2개 밟아요 (4→2, 2→1).
#       / \         그래서 이 트리의 최대 높이는 2 입니다.
#      2   6        노드로 세면 3이 나오니까, 어느 쪽으로 세고 있는지
#     / \ / \       한 번 확인하고 가세요.
#    1  3 5  7
#
# 빈 트리의 높이도 문제지가 정해뒀습니다. 아래 (1) 번에서 확인하시고요.
#
# 참고: main 의 case 2 가 `c = maxHeight(root);` 라서 **메뉴 변수를 덮어씁니다.**
# 높이가 0 이면 메뉴 루프가 거기서 끝나버려요. 검산기는 그 경우도 처리하니까
# 신경 안 쓰셔도 되는데, 직접 손으로 돌리실 때 헷갈릴 수 있어서 적어둡니다.

set -u
cd "$(dirname "$0")"

SRC=Q2_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

LABEL='최대 높이:'       # 메뉴 안내문은 "최대 높이 구하기" 라서 안 걸립니다.

# 레벨 순서로 적은 트리를, 프로그램에 흘려넣을 한 줄씩짜리로 바꿉니다.
# 스택 pop 순서로 번역하는 건 treeinput.sh 가 알아서 해요.
tree() {                 # tree "4 2 6 1 3 5 7"  ->  "4\n2\n6\n1\n3\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

check() {                # check "이름" "트리" "기대 높이"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "$LABEL" "$OUT")
	if judge "$name" "높이" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

shape() {                # shape "이름" "트리" "중위순회 기대값"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "중위순회" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
# 높이를 믿으려면 트리부터 맞아야 해요. 여기가 틀리면 아래는 볼 필요도 없습니다.
shape "문제지 그림" "4 2 6 1 3 5 7"           "1 2 3 4 5 6 7"

echo "=== 문제지 예시 ==="
check "문제지 그림" "4 2 6 1 3 5 7"           "2"

echo "=== 기본 ==="
check "한 노드" "1" "0"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 재귀가 맨 아래에서 마주치는 경우이고, 이 값이 정해져야
#     위의 모든 계산이 따라옵니다. 문제지가 이 값을 힌트로 직접 정해줬어요.
#     루트 자리에 문자 하나만 주면 빈 트리가 됩니다.
 check "빈 트리" "x" "-1"
#
# (2) 왼쪽으로만 한 줄로 내려가는 트리. 링크가 몇 개인지 손으로 세보시고요.
#     ※ 이 줄은 상철님이 고르신 트리(1-2-3-4 왼쪽 줄, 높이 3)를 새 표기로
#        옮겨적기만 한 거예요. 케이스도 기대값도 상철님이 정하신 그대로입니다.
 check "왼쪽으로만" "1 2 x 3 x 4" "3"
#
# (3) (2) 를 거울처럼 뒤집어서 오른쪽으로만 내려가는 트리. 한쪽만 테스트하면
#     반대쪽 경로가 한 번도 안 돌 수 있어요. 오전에 겪은 그 자리예요.
 check "오른쪽으로만" "1 x 2 x 3 x 4" "3"
#
# (4) 좌우 깊이가 다른 트리. 더 깊은 쪽이 답이 되는지 보는 자리입니다.
#     둘 중 큰 쪽을 안 고르고 한쪽만 돌려주는 풀이가 여기서 걸려요.
 check "좌우 깊이 다름" "1 x 2 3 4 5" "3"
#
# (5) (4) 를 좌우 반대로. 큰 쪽이 왼쪽일 때와 오른쪽일 때가 둘 다 돌아야 합니다.
 check "좌우 깊이 다름" "1 2 3 4 5 x x 6" "3"

summary
