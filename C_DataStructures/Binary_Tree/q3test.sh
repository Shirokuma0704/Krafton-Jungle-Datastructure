#!/usr/bin/env bash
# Q3 countOneChildNodes 검산기
#
#   bash q3test.sh        기대값 대조만 (빠름)
#   bash q3test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "트리" "기대 개수"
#     shape "이름" "트리" "중위순회 기대값"      입력이 내 생각대로 들어갔는지
#
# 트리 적는 법은 q2test.sh 와 같아요. **위에서 아래로, 왼쪽에서 오른쪽으로**
# 보이는 대로 적고, 중간에 빈 자리만 x 로 표시합니다. 뒤쪽 빈 자리는 생략해도 돼요.
#
#          50                적는 법:  50 20 60 10 30 x 80 x x 55
#         /  \
#       20    60             60 은 왼쪽이 비었으니 그 자리에 x 가 들어가고,
#      /  \     \            30 의 오른쪽부터 뒤쪽은 안 적어도 알아서 채워집니다.
#    10    30    80
#         /
#       55
#
# ★ "자식이 정확히 하나" 가 무슨 뜻인지가 이 문제의 전부입니다 ★
#
# 위 그림에서 답은 2 예요. 30 은 왼쪽만 있고, 60 은 오른쪽만 있습니다.
# 자식이 둘 다 있는 노드(50, 20)도, 아예 없는 잎(10, 55, 80)도 안 셉니다.
# 한쪽만 있는 노드만이에요. 어느 쪽이 비었는지는 상관없습니다.
#
# 출력 끝에 마침표가 붙어서 나오는데("... 개수: 2."), 검산기가 떼고 비교합니다.

set -u
cd "$(dirname "$0")"

SRC=Q3_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

LABEL='노드 개수:'       # 메뉴 안내문은 "노드 개수 세기." 라서 안 걸립니다.

tree() {                 # tree "50 20 60"  ->  "50\n20\n60\nx\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

check() {                # check "이름" "트리" "기대 개수"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "$LABEL" "$OUT")
	got=${got%.}         # 출력 끝의 마침표를 뗍니다

	if judge "$name" "개수" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

shape() {                # shape "이름" "트리" "중위순회 기대값"
	local name="$1" t1="$2" want="$3" inp got

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "중위순회" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
# 개수를 믿으려면 트리부터 맞아야 해요. 여기가 틀리면 아래는 볼 필요도 없습니다.
shape "문제지 그림" "50 20 60 10 30 x 80 x x 55" "10 20 55 30 50 60 80"

echo "=== 문제지 예시 ==="
check "문제지 그림" "50 20 60 10 30 x 80 x x 55" "2"

echo "=== 기본 ==="
check "한 노드" "1" "0"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
#
# (1) 빈 트리일 때. 재귀가 맨 아래에서 마주치는 경우이고, 여기서 NULL 을
#     안 걸러내면 없는 자식을 들여다보게 됩니다.
 check "빈 트리" "" "0"
#
# (2) 모든 노드가 자식을 둘씩 갖는 트리. 세면 안 되는 것을 안 세는지 보는
#     자리예요. 조건을 "자식이 있으면" 으로 잘못 쓰면 여기서 부풀어 오릅니다.
 check "자식이 다 둘씩" "1 2 3 4 5 6 7" "0"
#
# (3) 왼쪽으로만 한 줄로 내려가는 트리. 줄에 선 노드들이 전부 왼쪽 자식
#     하나씩만 갖고, 맨 아래 잎만 예외입니다. 몇 개인지 세보세요.
 check "왼쪽으로만" "1 2 x 3 x 4 x 5" "4"
#
# (4) (3) 을 거울처럼 뒤집어서 오른쪽으로만 내려가는 트리. "어느 쪽이 비었든
#     하나만 있으면 센다" 가 지켜지는지 보는 자리예요. 한쪽만 테스트하면
#     반대쪽 조건이 한 번도 안 돌 수 있습니다.
 check "왼쪽으로만" "1 x 2 x 3 x 4 x 5" "4"
#
# (5) 루트 자신이 자식 하나만 갖는 트리. 루트도 세는 대상인지 확인하는
#     자리입니다. 재귀를 자식부터 시작하면 루트가 빠져요.
 check "루트가 자식 하나" "1 2 x" "1"

summary
