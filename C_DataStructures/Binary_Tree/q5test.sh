#!/usr/bin/env bash
# Q5 mirrorTree 검산기
#
#   bash q5test.sh        기대값 대조만 (빠름)
#   bash q5test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "넣을 트리" "뒤집히고 나서의 트리"
#     shape "이름" "트리"                 내가 적은 대로 만들어졌는지만 확인
#
# 트리 적는 법은 q2~q4 와 같아요. 보이는 대로 적고, 중간 빈 자리만 x 로 표시합니다.
#
# ★ 앞의 넷과 검산 방식이 다릅니다 ★
#
# mirrorTree 는 void 예요. 돌려주는 값이 없고 **트리 자체를 바꿉니다.**
# 그래서 "돌려받은 값" 이 아니라 **바뀐 트리를 다시 찍어서** 비교해요.
# main 이 뒤집은 뒤에 printTree 를 한 번 더 불러주니까 그 줄을 봅니다.
#
# 다만 적으실 때는 그냥 **트리를 트리로** 적으시면 돼요. 기대값 칸에도 뒤집힌
# 트리를 그대로 적으시면, 찍혀 나올 줄로 바꾸는 건 검산기가 알아서 합니다.
# 입력 칸과 기대값 칸이 같은 언어예요.
#
# 참고로 문제지가 알려준 성질 하나 — 거울상으로 뒤집으면 중위 순회 결과가
# 정확히 거꾸로 뒤집힙니다. 손으로 확인하실 때 쓰시면 편해요.
#
#        4          중위순회  5 6 4 3 2 1           4          중위순회  1 2 3 4 6 5
#       / \                                        / \
#      5   2       적는 법: 4 5 2 x 6 3 1         2   5
#       \  / \                                    / \   \
#        6 3  1                                  1   3   6
#
# ★ 규정 ★
#
# 문제지: "중간 트리나 임시 트리를 새로 만들면 안 됩니다."
#
# 임시 **포인터** 는 규정 안쪽이에요. BTNode *temp; 는 트리가 아니라 스택에 놓인
# 변수 하나고, 가리키기만 할 뿐 노드를 안 만듭니다. 갈리는 기준은 malloc 이나
# createBTNode() 가 등장하느냐예요. 안 나오면 있는 노드의 연결만 바꾼 겁니다.
#
# 알아두실 제약 하나: main 의 case 2 가 뒤집고 찍은 다음 removeAll 을 해버려서
# **한 세션에서 두 번 뒤집을 수가 없습니다.** 두 번 뒤집으면 원래대로 돌아오는지는
# 여기서 못 봐요. 확인하고 싶으시면 임시로 case 2 의 removeAll 을 주석 처리하고
# 손으로 2를 두 번 눌러보세요. (확인 끝나면 되돌려 두시고요)

set -u
cd "$(dirname "$0")"

SRC=Q5_E_BT.c
. ../common/testlib.sh
. ../common/treeinput.sh

tree() {                 # tree "4 5 2 x 6 3 1"  ->  "4\n5\n2\nx\n..."
	local t out=""
	for t in $(lv_to_preorder "$1"); do out+="$t\n"; done
	printf '%s' "$out"
}

# 기대값도 트리로 적습니다. 찍혀 나올 줄로 바꾸는 건 여기서 알아서 해요.
check() {                # check "이름" "넣을 트리" "뒤집히고 나서의 트리"
	local name="$1" t1="$2" want got inp

	want=$(lv_to_inorder "$3")
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "뒤집은 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "뒤집은 뒤" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

# 내가 적은 트리대로 프로그램이 만들었는지만 봅니다. 기대값은 안 적어도 돼요.
shape() {                # shape "이름" "트리"
	local name="$1" t1="$2" want got inp

	want=$(lv_to_inorder "$t1")
	[ -z "$want" ] && want="$EMPTY"

	inp="1\n$(tree "$t1")0\n"
	run "$inp"
	died "$name" && return

	got=$(pick "만들어진 이진 트리" "$OUT")
	[ -z "$got" ] && got="$EMPTY"

	if judge "$name" "만들어진 트리" "$got" "$want"; then
		ok "$name"
	fi
}

echo "=== 입력이 내 생각대로 들어갔는지 ==="
# 뒤집힌 결과를 믿으려면 뒤집기 전 트리부터 맞아야 해요.
shape "문제지 tree1" "4 5 2 x 6 3 1"

echo "=== 문제지 예시 ==="
# 기대값도 트리예요. 위 그림의 오른쪽(거울상) 트리를 그대로 적은 겁니다.
check "문제지 그림" "4 5 2 x 6 3 1" "4 2 5 1 3 6"

echo "=== 기본 ==="
check "한 노드" "1" "1"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
# 빈 트리는 양쪽 칸 모두 "x" 나 "" 로 적으시면 됩니다.
#
# (1) 빈 트리일 때. 바꿀 게 없으니 그냥 돌아와야 하는 자리예요.
#     여기서 NULL 을 안 걸러내면 없는 자식을 만지게 됩니다.
 check "빈 트리" "" ""
#
# (2) 왼쪽으로만 한 줄로 내려가는 트리. 뒤집으면 오른쪽 줄이 되어야 해요.
#     방향이 실제로 바뀌는지를 제일 단순하게 보는 자리입니다.
 check "왼쪽으로만" "1 2 x 3 x 4" "1 x 2 x 3 x 4"
#
# (3) 자식이 한쪽만 있는 노드가 섞인 트리. 있는 자식과 없는 자리(NULL)를
#     맞바꿔야 하는 자리예요. "둘 다 있을 때만 바꾼다" 로 짜면 여기서 걸립니다.
 check "한쪽 자식만" "1 x 2 3 x x 4" "1 2 x x 3 4 x"
#
# (4) 세 층 이상 되는 트리. 루트만 바꾸고 안 내려가는 구현이 여기서 드러나요.
#     위 두 층만 보면 맞아 보이는 모양으로 만들어보세요.
# check "깊은 트리" "?" "?" 앞에서 많이함?
#
# (5) 모든 노드가 자식을 둘씩 갖는 트리. (3) 의 반대쪽이고, 빠뜨리는 노드
#     없이 전부 뒤집히는지 봅니다.
 check "자식이 다 둘씩" "1 -2 3 -4 -5 6 7" "1 3 -2 7 6 -5 -4"

summary
