#!/usr/bin/env bash
# BST Q4 postOrderIterativeS1 검산기
#
#   bash q4test.sh        기대값 대조만 (빠름)
#   bash q4test.sh -v     valgrind 까지 (WSL 에서만 됩니다)
#
#     check "이름" "넣는 순서" "기대 후위순회"
#     twice "이름" "넣는 순서" "기대 후위순회"    2번을 두 번 눌러봅니다
#
# 입력은 앞의 검산기들과 같아요. 트리 모양이 아니라 **넣는 순서**를 적습니다.
#
#     20 15 50 10 18 25 80  을 순서대로 넣으면
#
#              20                 후위 순회: 10 18 15 25 80 50 20
#            /    \
#          15      50             왼쪽 전부 -> 오른쪽 전부 -> 그다음에 나
#         /  \    /  \
#       10    18 25   80
#
#     bash ../common/bstinput.sh "20 15 50 10 18 25 80"   로 그려볼 수 있어요
#
# ★ 기대값을 적을 때 쓸 수 있는 자가검증 ★
#
# 후위 순회는 "나를 마지막에" 라서, **맨 끝에 나오는 값은 반드시 루트**예요.
# 그리고 루트는 제일 먼저 넣은 값이고요. 그러니 기대값을 다 적은 다음
# 마지막 숫자와 넣는 순서의 첫 숫자를 맞춰보세요. 다르면 거기서 이미 틀린 거예요.
#
# 같은 요령으로, 전위(Q3)는 **첫 값**이 루트였어요. 중위(Q2)는 오름차순이었고요.
# 세 순회가 각각 다른 자리에 표지를 남기는 셈이에요 ( ˶ˆᗜˆ˵ )
#
# ★ Q5 에서 그대로 재사용됩니다 ★
#
# 문제지에 이렇게 적혀 있어요 — "4번과 결과는 같습니다. 스택을 몇 개 쓰느냐만
# 다릅니다." 그러니 여기서 한 번 고민해서 채운 기대값은 q5test.sh 에 통째로
# 복사하시면 돼요. 경계 케이스를 두 번 짜실 필요 없습니다.
#
# ★ 문제지 조건 ★
#
# "스택 하나를 사용해서 … 반복문 C 함수 postOrderIterativeS1() 을 작성하세요."
# "시작할 때 스택이 비어 있지 않으면 먼저 비워야 합니다."
#
# 스택 **하나**라는 게 Q5 와 갈리는 지점이에요. 그리고 main 의 case 2 는
# removeAll 을 안 해서 2번을 여러 번 누를 수 있으니, twice 로 두 번 눌러봅니다.

set -u
cd "$(dirname "$0")"

SRC=Q5_F_BST.c
. ../common/testlib.sh
. ../common/bstinput.sh

LABEL='순회 결과:'       # 메뉴 안내문은 "후위 순회 출력;" 이라 안 걸립니다.

feed() {                 # feed "20 15 50"  ->  "1\n20\n1\n15\n1\n50\n"
	local v out=""
	for v in $1; do out+="1\n$v\n"; done
	printf '%s' "$out"
}

grab() {                 # grab 1 "$OUT"
	printf '%s\n' "$2" | grep "$LABEL" | sed -n "$1p" | sed 's/.*: //; s/[[:space:]]*$//'
}

check() {                # check "이름" "넣는 순서" "기대 후위순회"
	local name="$1" seq="$2" want="$3" inp got

	inp="$(feed "$seq")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(grab 1 "$OUT")
	[ -z "$got" ] && got="$EMPTY"
	[ -z "$want" ] && want="$EMPTY"

	if judge "$name" "후위순회" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

twice() {                # twice "이름" "넣는 순서" "기대 후위순회"
	local name="$1" seq="$2" want="$3" inp first second

	inp="$(feed "$seq")2\n2\n0\n"
	run "$inp"
	died "$name" && return

	first=$(grab 1 "$OUT");  [ -z "$first" ]  && first="$EMPTY"
	second=$(grab 2 "$OUT"); [ -z "$second" ] && second="$EMPTY"
	[ -z "$want" ] && want="$EMPTY"

	if judge "$name (첫 번째)" "후위순회" "$first" "$want"; then
		if judge "$name (두 번째)" "후위순회" "$second" "$want"; then
			ok "$name"
		fi
	fi

	vgcheck "$inp" "$name"
}

echo "=== 문제지 예시 ==="
check "문제지 그림" "20 15 50 10 18 25 80" "10 18 15 25 80 50 20"

echo "=== 기본 ==="
check "한 노드" "7" "7"

echo "=== 내가 만든 경계 케이스 ==="
# ? 자리를 채우고 앞의 # 을 지우면서 하나씩 돌려보세요.
# 한 번에 다 풀지 마시고, 하나 채우고 한 번 돌리는 식으로요.
# 아무것도 안 찍혀야 하면 기대값 자리에 "$EMPTY" 나 "" 를 쓰세요.
#
# (1) 아무것도 안 넣고 바로 2번을 누른 경우예요. 넣는 순서 자리를 비워두시면 됩니다.
#     빈 스택에서 pop 을 부르면 그대로 터지는 자리이기도 해요.
 check "빈 트리" "" ""
#
# (2) 내림차순으로만 넣으면 왼쪽으로 한 줄인 트리가 됩니다. 후위 순회는 나를
#     마지막에 찍으니까, 제일 깊은 곳에서 거슬러 올라오는 모양이 돼요.
#     Q3 의 같은 케이스와 나란히 놓고 보시면 차이가 선명합니다.
 check "내림차순" "5 4 3 2 1 0" "0 1 2 3 4 5"
#
# (3) (2) 를 거꾸로 오름차순으로만 넣으면 오른쪽 한 줄이 됩니다. 이쪽은 왼쪽
#     자식이 한 번도 안 나오는 경우라, 왼쪽을 아예 안 보는 코드도 통과해버려요.
#     그래서 (2) 와 반드시 짝으로 두셔야 합니다.
 check "오름차순" "-5 1 2 3 4 5" "5 4 3 2 1 -5"
#
# (4) 같은 값을 여러 번 넣은 경우예요. insertBSTNode 가 두 번째부터 버리니까
#     결과에 몇 번 나와야 하는지 먼저 정하고 적으세요.
 check "중복 값" "1 1 1 1 1" "1"
#
# (5) Q2, Q3 에서 쓰신 6노드 트리(50 60 20 10 40 30)예요. 왼쪽 자식이 다시
#     오른쪽 자식을 갖는 모양이라, 얕은 트리에서는 안 드러나던 차이가 여기서
#     나옵니다. 후위는 기대값이 또 다르니 새로 세어보세요.
 check "복잡한 갈래" "50 60 20 10 40 30" "10 30 40 20 60 50"
#
# (6) 2번을 두 번 누르는 경우예요. 문제지가 "스택이 비어 있지 않으면 먼저
#     비우라"고 한 자리입니다. check 대신 twice 를 쓰시고 기대값은 한 번
#     분량만 적으세요. 빈 트리로 두면 함수가 첫 줄에서 바로 나가버려서
#     스택도 free 도 한 번을 안 거치니, 트리를 하나 넣어주세요.
 twice "두 번 순회" "50 60 20 10 40 30" "10 30 40 20 60 50"

summary
