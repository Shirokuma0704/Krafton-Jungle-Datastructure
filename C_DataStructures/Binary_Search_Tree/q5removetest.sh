LABEL='순회 결과:'

feed() {                 # feed "20 15 50"  ->  "1\n20\n1\n15\n1\n50\n"
	local v out=""
	for v in $1; do out+="1\n$v\n"; done
	printf '%s' "$out"
}

fdel() {                 # fdel "15 50"  ->  "3\n15\n3\n50\n"
	local v out=""
	for v in $1; do out+="3\n$v\n"; done
	printf '%s' "$out"
}

grab() {                 # grab 1 "$OUT"
	printf '%s\n' "$2" | grep "$LABEL" | sed -n "$1p" | sed 's/.*: //; s/[[:space:]]*$//'
}

del() {                  # del "이름" "넣는 순서" "지울 값들" "기대 후위순회"
	local name="$1" seq="$2" kill="$3" want="$4" inp got

	inp="$(feed "$seq")$(fdel "$kill")2\n0\n"
	run "$inp"
	died "$name" && return

	got=$(grab 1 "$OUT")
	[ -z "$got" ] && got="$EMPTY"
	[ -z "$want" ] && want="$EMPTY"

	if judge "$name" "삭제 뒤 후위순회" "$got" "$want"; then
		ok "$name"
	fi

	vgcheck "$inp" "$name"
}

